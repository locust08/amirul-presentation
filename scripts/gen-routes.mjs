/**
 * Writes the thin route files in src/pages for each language.
 * Every route just renders a shared view from src/views with `lang` set,
 * so English (/...) and Chinese (/zh/...) never drift apart.
 *
 *   node scripts/gen-routes.mjs
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../src/pages", import.meta.url));
const views = fileURLToPath(new URL("../src/views", import.meta.url));

const routes = [
	{ file: "index.astro", view: "HomeView" },
	{ file: "restaurants/index.astro", view: "RestaurantsView" },
	{ file: "restaurants/[slug].astro", view: "RestaurantView", slug: "restaurants" },
	{ file: "promotions/index.astro", view: "PromotionsView" },
	{ file: "promotions/[slug].astro", view: "PromotionView", slug: "promotions" },
	{ file: "contact.astro", view: "ContactView" },
	{ file: "[slug].astro", view: "PageView", slug: "pages" },
	{ file: "404.astro", view: "NotFoundView" },
];

for (const lang of ["en", "zh"]) {
	for (const route of routes) {
		const target = join(root, lang === "en" ? "" : lang, route.file);
		mkdirSync(dirname(target), { recursive: true });
		const importPath = relative(dirname(target), join(views, `${route.view}.astro`));
		const lines = ["---", "// Generated by scripts/gen-routes.mjs — edit the view, not this file.", `import View from "${importPath}";`];
		if (route.slug) {
			const lib = relative(dirname(target), fileURLToPath(new URL("../src/lib/content", import.meta.url)));
			const notFound = lang === "en" ? "/404" : `/${lang}/404`;
			const reserved = route.slug === "pages" ? ' || ["home", "contact", "404"].includes(slug)' : "";
			lines.splice(2, 0, `import { getLocalizedEntry } from "${lib}";`);
			lines.push(
				"",
				"const slug = Astro.params.slug;",
				`if (!slug${reserved}) return Astro.rewrite("${notFound}");`,
				`const entry = await getLocalizedEntry("${route.slug}", slug, "${lang}", Astro);`,
				`if (!entry) return Astro.rewrite("${notFound}");`,
			);
		}
		let langExpr = `"${lang}"`;
		if (route.view === "NotFoundView") {
			lines.push("", "Astro.response.status = 404;");
			if (lang === "en") {
				// Unknown /zh/... URLs land here too — answer in Chinese.
				lines.push('const lang = /^\\/zh(\\/|$)/.test(Astro.url.pathname) ? "zh" : "en";');
				langExpr = "{lang}";
			}
		}
		lines.push("---", "", route.slug ? `<View lang=${langExpr} slug={slug} />` : `<View lang=${langExpr} />`, "");
		writeFileSync(target, lines.join("\n"));
	}
}
console.log("Routes written.");
