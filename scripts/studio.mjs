/**
 * Open the Stacki visual editor on this project's own files.
 *
 *   npm run studio            → http://localhost:4350/studio
 *
 * Stacki's own `npm --prefix studio run dev` edits a disposable copy of the
 * site (a draft workspace for hosted publishing). This script does what the
 * Stacki desktop app does instead: it runs the site's dev server with the
 * Studio integration added, so edits are saved straight into src/ and show up
 * in `git status` like any other change.
 */
import { spawn } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const studioDist = path.join(root, "studio", "dist");
const port = Number(process.env.STUDIO_PORT ?? 4350);

if (!existsSync(path.join(studioDist, "integration.mjs"))) {
	console.error("Stacki Studio is not built. Run: npm --prefix studio ci && npm --prefix studio run build");
	process.exit(1);
}

const options = { root, assets: studioDist, port, editing: "source" };
const config = `// Generated by scripts/studio.mjs — not committed.
import config from "./astro.config.mjs";
import studio from ${JSON.stringify(pathToFileURL(path.join(studioDist, "integration.mjs")).href)};

export default {
	...config,
	devToolbar: { enabled: false },
	integrations: [...(config.integrations ?? []), studio(${JSON.stringify(options)})],
};
`;
writeFileSync(path.join(root, "astro.studio.config.mjs"), config);
console.log(`Stacki Studio: http://localhost:${port}/studio  (editing the files in ${root})`);

const child = spawn(
	process.execPath,
	[path.join(root, "node_modules/astro/bin/astro.mjs"), "dev", "--config", "./astro.studio.config.mjs", "--port", String(port), "--host", "127.0.0.1", "--ignore-lock"],
	{ cwd: root, stdio: "inherit", env: { ...process.env, ASTRO_TELEMETRY_DISABLED: "1" } },
);
for (const signal of ["SIGINT", "SIGTERM", "SIGHUP"]) process.once(signal, () => child.kill("SIGTERM"));
child.on("exit", (code) => process.exit(code ?? 0));
